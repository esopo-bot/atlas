// Menu em duas partes.
//
// As páginas da camada são escritas à mão, na ordem de leitura: o que se usa
// todo dia primeiro. Página nova da CAMADA só aparece depois de ganhar uma
// linha aqui.
//
// As subpastas de conhecimento/ são da casa — a wiki que a skill gera, as
// notas, as decisões — e os nomes são livres. Por isso elas não podem ser
// lista fixa: o menu as descobre no disco a cada construção.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const raiz = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const CONHECIMENTO = path.join(raiz, 'conhecimento');

// O H1 do LEIAME da subpasta vira o rótulo da categoria; sem ele, o nome da
// pasta serve. O LEIAME já é a convenção da casa para dizer o que mora ali.
function rotulo(pasta, nome) {
  const leiame = path.join(pasta, 'LEIAME.md');
  if (fs.existsSync(leiame)) {
    const titulo = fs.readFileSync(leiame, 'utf8').match(/^#\s+(.+)$/m);
    if (titulo) return titulo[1].trim();
  }
  return nome;
}

function subpastasDaCasa() {
  if (!fs.existsSync(CONHECIMENTO)) return [];
  return fs
    .readdirSync(CONHECIMENTO, { withFileTypes: true })
    .filter((entrada) => entrada.isDirectory())
    .map((entrada) => entrada.name)
    .sort() // ordem estável: o menu não dança entre construções
    .map((nome) => {
      const pasta = path.join(CONHECIMENTO, nome);
      const temPagina = fs.readdirSync(pasta).some((f) => f.endsWith('.md'));
      // Categoria sem página derruba a construção — pasta vazia fica fora.
      if (!temPagina) return null;
      return {
        type: 'category',
        label: rotulo(pasta, nome),
        items: [{ type: 'autogenerated', dirName: `conhecimento/${nome}` }],
      };
    })
    .filter(Boolean);
}

const daCamada = [
  'conhecimento/comece-aqui',
  'fluxos/abrir-e-fechar-a-sessao',
  'conhecimento/regras-da-camada',
  'conhecimento/mapa-do-repositorio',
  'fluxos/templates',
  'fluxos/investigacao-de-incidente',
  'fluxos/historia-em-issue',
  'conhecimento/zero-que-mente',
  'conhecimento/skills-da-camada',
  'conhecimento/skills-criar-e-testar',
  'conhecimento/ganchos',
  'conhecimento/plugins-oficiais-do-claude-code',
  'conhecimento/mcp',
  'conhecimento/subagentes',
];

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  documentacao: [...daCamada, ...subpastasDaCasa()],
};

export default sidebars;
