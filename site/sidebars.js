// Menu em duas partes.
//
// As páginas da camada são escritas à mão, na ordem de leitura: o que se usa
// todo dia primeiro. Página nova da CAMADA só aparece depois de ganhar uma
// linha aqui.
//
// As subpastas de conhecimento/ são do repositório — a wiki que a skill gera,
// as notas, as decisões — e os nomes são livres. Por isso elas não podem ser
// lista fixa: o menu as descobre no disco a cada construção.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const raiz = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const CONHECIMENTO = path.join(raiz, 'conhecimento');

// O H1 do LEIAME da subpasta vira o rótulo da categoria; sem ele, o nome da
// pasta serve. O LEIAME já é a convenção do repositório para dizer o que mora
// ali.
function rotulo(pasta, nome) {
  const leiame = path.join(pasta, 'LEIAME.md');
  if (fs.existsSync(leiame)) {
    const titulo = fs.readFileSync(leiame, 'utf8').match(/^#\s+(.+)$/m);
    if (titulo) return titulo[1].trim();
  }
  return nome;
}

function subpastasDaCasa() {
  if (!fs.existsSync(CONHECIMENTO)) return [];
  return fs
    .readdirSync(CONHECIMENTO, { withFileTypes: true })
    .filter((entrada) => entrada.isDirectory())
    .map((entrada) => entrada.name)
    .sort() // ordem estável: o menu não dança entre construções
    .map((nome) => {
      const pasta = path.join(CONHECIMENTO, nome);
      const temPagina = fs.readdirSync(pasta).some((f) => f.endsWith('.md'));
      // Categoria sem página derruba a construção — pasta vazia fica fora.
      if (!temPagina) return null;
      return {
        type: 'category',
        label: rotulo(pasta, nome),
        items: [{ type: 'autogenerated', dirName: `conhecimento/${nome}` }],
      };
    })
    .filter(Boolean);
}

// Página de primeiro nível que a lista escrita à mão não cita.
//
// Acontece com módulo opcional: ele instala uma página que só existe onde
// alguém o pediu, e por isso ela NÃO pode ganhar linha fixa aqui — a linha
// derrubaria a construção de todo repositório que não instalou o módulo.
//
// Sem esta descoberta a página vira órfã, e órfã é o pior dos dois mundos:
// medido, a rota é gerada e nenhum menu leva até ela. Ela cobra contexto de
// toda sessão e não entrega a nenhuma.
function paginasNaoCitadas(citadas) {
  const conhecidas = new Set(citadas);
  if (!fs.existsSync(CONHECIMENTO)) return [];
  return fs
    .readdirSync(CONHECIMENTO, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.md') && e.name !== 'LEIAME.md')
    .map((e) => `conhecimento/${e.name.slice(0, -3)}`)
    .filter((id) => !conhecidas.has(id))
    .sort(); // ordem estável: o menu não dança entre construções
}

// A ordem é de leitura, não de assunto: o que se usa todo dia primeiro e o
// que se consulta depois. O catálogo subiu para o
// terceiro lugar de propósito — ele é o que evita reescrever o que já existe,
// e página que resolve isso no fim da lista chega tarde demais.
const daCamada = [
  'conhecimento/comece-aqui',
  'conhecimento/abrir-e-fechar-a-sessao',
  'conhecimento/skills-da-camada',
  'conhecimento/regras-da-camada',
  'conhecimento/mapa-do-repositorio',
  'conhecimento/investigacao-de-incidente',
  'conhecimento/falso-negativo',
  'conhecimento/historia-em-issue',
  'conhecimento/rodar-uma-execucao',
  'conhecimento/skills-criar-e-testar',
  'conhecimento/ganchos',
  'conhecimento/paridade-entre-agentes',
  'conhecimento/estado-que-nao-viaja',
  'conhecimento/mudar-de-maquina',
  'conhecimento/mcp',
  'conhecimento/subagentes',
];

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  documentacao: [
    ...daCamada,
    ...paginasNaoCitadas(daCamada),
    ...subpastasDaCasa(),
  ],
};

export default sidebars;
